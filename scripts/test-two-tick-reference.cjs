'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const file = path.join(__dirname, 'two-tick-reference.cjs');
const ref = fs.existsSync(file) ? require(file) : {};
const id = (a,b,h) => (a*70+b)*70+h;
assert.equal(typeof ref.terminal, 'function', 'terminal API must exist');
assert.equal(ref.terminal(id(0,69,0)), true, 'shared initial cell');
assert.equal(ref.terminal(id(0,69,1)), true, 'cardinal initial contact');
assert.equal(ref.terminal(id(0,69,11)), false, 'diagonal is not contact');
assert.equal(ref.terminal(id(0,69,59)), true, 'second pursuer contact');
console.log('PASS literal terminal contact tests');
assert.equal(typeof ref.transition, 'function', 'transition API must exist');
assert.equal(ref.transition(id(0,69,0), 1), -1, 'terminal cannot move');
assert.equal(ref.transition(id(22,44,0), 0), -1, 'north border');
assert.equal(ref.transition(id(22,44,0), 3), -1, 'west border');
assert.equal(ref.transition(id(22,44,0), 7), -1, 'unknown action');
assert.equal(ref.transition(id(0,69,22), 1), id(1,59,23), 'both chase OLD human');
assert.equal(ref.transition(id(1,59,23), 2), id(2,49,33), 'second tick chases updated OLD human');
assert.equal(ref.transition(id(0,0,2), 3), id(1,1,1), 'shared capture endpoint retained');
assert.equal(ref.transition(id(0,0,2), 4), id(1,1,2), 'adjacent capture endpoint retained');
console.log('PASS literal transition tests');
assert.deepEqual(ref.decide(0, []), {action:-1,mask:[false,false,false,false,false],depth1:[false,false,false,false,false],depth2:[false,false,false,false,false],horizon:0});
assert.deepEqual(ref.decide(1612, [-1,1,0,2,-2]), {action:3,mask:[false,true,true,true,true],depth1:[false,false,false,false,false],depth2:[false,false,false,false,false],horizon:0});
assert.deepEqual(ref.decide(7010, [0,-2,0,2,-2]), {action:0,mask:[true,false,false,false,false],depth1:[true,false,false,false,false],depth2:[false,false,false,false,false],horizon:1});
assert.deepEqual(ref.decide(2, [0,0,0,0,0]), {action:1,mask:[false,true,true,false,false],depth1:[false,true,true,false,false],depth2:[false,true,true,false,false],horizon:2});
// First east remains eligible although a future west/stay would be unsafe.
assert.equal(ref.decide(2, [0,10,0,100,0]).action,1);
assert.equal(ref.terminal(ref.transition(ref.transition(2,1),3)),true);
assert.equal(ref.terminal(ref.transition(ref.transition(2,1),1)),false);
console.log('PASS literal fallback, existential and tie regression fixtures');
